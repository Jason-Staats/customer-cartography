USE uci;

# COUNT SOURCE ROWS WITH MISSING PRODUCT DESCRIPTIONS
# MISSING MEANS NULL, EMPTY, OR SPACES-ONLY.
# PREVIOUSLY OBSERVED: 1454 SOURCE ROWS WITH EMPTY DESCRIPTIONS.
SELECT COUNT(*) AS missing_description_rows
FROM retail_stg
WHERE NULLIF(TRIM(product_description), '') IS NULL;


# COUNT DISTINCT STOCK CODES APPEARING ON MISSING-DESCRIPTION ROWS
# PREVIOUSLY OBSERVED: 960 STOCK CODES ON EMPTY-DESCRIPTION ROWS.
# THESE STOCK CODES MAY HAVE POPULATED DESCRIPTIONS ON OTHER ROWS.
SELECT COUNT(DISTINCT stock_code) AS stock_codes_with_missing_descriptions
FROM retail_stg
WHERE NULLIF(TRIM(product_description), '') IS NULL;


# COUNT ALL DISTINCT SOURCE STOCK CODES
# PREVIOUSLY OBSERVED: 3958 DISTINCT STOCK CODES.
SELECT COUNT(DISTINCT stock_code) AS total_stock_codes
FROM retail_stg;


# IDENTIFY STOCK CODES WITH MULTIPLE DISTINCT NONBLANK DESCRIPTIONS
# TRIM LEADING AND TRAILING SPACES FOR COMPARISON.
# RETURNED ROWS REQUIRE DESCRIPTION SELECTION, NOT AUTOMATIC EXCLUSION.
SELECT
    stock_code,
    COUNT(DISTINCT TRIM(product_description)) AS description_count
FROM retail_stg
WHERE NULLIF(TRIM(product_description), '') IS NOT NULL
GROUP BY stock_code
HAVING COUNT(DISTINCT TRIM(product_description)) > 1
ORDER BY
    description_count DESC,
    stock_code;


# OPTIONAL: INVESTIGATE DESCRIPTIONS FOR SELECTED STOCK CODES
# COUNT SOURCE ROWS FOR EACH TRIMMED NONBLANK DESCRIPTION.
# FIRST_SEEN AND LAST_SEEN REFER TO SOURCE INVOICE TIMESTAMPS.
SELECT
    stock_code,
    TRIM(product_description) AS product_description,
    COUNT(*) AS source_row_count,
    MIN(invoice_date) AS first_seen,
    MAX(invoice_date) AS last_seen
FROM retail_stg
WHERE stock_code IN (
    '20713',
    '23084',
    '21830',
    '85175',
    '21181'
)
  AND NULLIF(TRIM(product_description), '') IS NOT NULL
GROUP BY
    stock_code,
    TRIM(product_description)
ORDER BY
    stock_code,
    source_row_count DESC,
    product_description;


# IDENTIFY STOCK CODES WITH NO NONBLANK DESCRIPTION ANYWHERE IN STAGING
# ALL SOURCE DESCRIPTIONS FOR THESE CODES ARE NULL, EMPTY, OR SPACES-ONLY.
# THESE ARE CANDIDATES FOR EXCLUSION; REVIEW THE CHECK BELOW.
SELECT
    stock_code
FROM retail_stg
GROUP BY stock_code
HAVING COUNT(NULLIF(TRIM(product_description), '')) = 0
ORDER BY stock_code;


# CHECK EXCLUSION CANDIDATES FOR NONZERO OR MISSING PRICES
# AND FOR POPULATED CUSTOMER IDS.
# VALIDATION: EXPECTED ZERO ROWS.
# INVESTIGATE ANY RESULTS BEFORE ACCEPTING THE EXCLUSION.
SELECT
    stock_code,
    SUM(
        CASE WHEN unit_price <> 0
             THEN 1 ELSE 0 END
    ) AS nonzero_price_rows,
    SUM(
        CASE WHEN unit_price IS NULL
             THEN 1 ELSE 0 END
    ) AS missing_price_rows,
    SUM(
        CASE WHEN NULLIF(TRIM(customer_id), '') IS NOT NULL
             THEN 1 ELSE 0 END
    ) AS populated_customer_rows
FROM retail_stg
WHERE stock_code IN (
    SELECT stock_code
    FROM retail_stg
    GROUP BY stock_code
    HAVING COUNT(NULLIF(TRIM(product_description), '')) = 0
)
GROUP BY stock_code
HAVING
       nonzero_price_rows > 0
    OR missing_price_rows > 0
    OR populated_customer_rows > 0
ORDER BY stock_code;


# TEMPORARY-TABLE WORKFLOW
# START IN A CONNECTION WHERE THESE TEMPORARY TABLES DO NOT EXIST.
# RUN ALL REMAINING STEPS IN THE SAME CONNECTION.


# STEP 1: COUNT SOURCE ROWS FOR EACH TRIMMED NONBLANK DESCRIPTION
# EXCLUDE NULL, EMPTY, AND SPACES-ONLY DESCRIPTIONS.
# FREQUENCY COUNTS ALL SOURCE ROWS, INCLUDING RETURNS AND ADJUSTMENTS.

# DESCRIPTION GROUPING USES THE SOURCE COLUMN'S COLLATION.
# WITH utf8mb4_0900_ai_ci, CASE AND ACCENT DIFFERENCES
# DO NOT CREATE SEPARATE DESCRIPTION GROUPS.
# TRIM REMOVES LEADING AND TRAILING SPACES BEFORE GROUPING.

# THIS DIFFERS FROM THE BINARY COMPARISONS USED TO IDENTIFY
# EXACT SOURCE DUPLICATES IN transaction_cleaning.sql.
# RETAIL_STG REMAINS UNCHANGED.
CREATE TEMPORARY TABLE product_description_counts AS
SELECT
    stock_code,
    TRIM(product_description) AS product_description,
    COUNT(*) AS description_count
FROM retail_stg
WHERE NULLIF(TRIM(product_description), '') IS NOT NULL
GROUP BY
    stock_code,
    TRIM(product_description);


# OPTIONAL: INSPECT DESCRIPTION FREQUENCIES
SELECT
    stock_code,
    product_description,
    description_count
FROM product_description_counts
ORDER BY
    stock_code,
    description_count DESC,
    product_description;


# STEP 2: RANK DESCRIPTIONS BY FREQUENCY WITHIN EACH STOCK CODE
# RANK 1 IDENTIFIES THE MOST FREQUENT DESCRIPTION(S).
# DENSE_RANK PRESERVES TIES FOR LATER REVIEW.
CREATE TEMPORARY TABLE product_description_ranked AS
SELECT
    stock_code,
    product_description,
    description_count,
    DENSE_RANK() OVER (
        PARTITION BY stock_code
        ORDER BY description_count DESC
    ) AS description_rank
FROM product_description_counts;


# OPTIONAL: INSPECT THE MOST FREQUENT DESCRIPTION(S) FOR EACH STOCK CODE
SELECT
    stock_code,
    product_description,
    description_count,
    description_rank
FROM product_description_ranked
WHERE description_rank = 1
ORDER BY
    stock_code,
    product_description;


# STEP 3: RETAIN TOP-RANKED DESCRIPTIONS AND COUNT THEM PER STOCK CODE
# TIED_DESCRIPTIONS = 1 MEANS THERE IS ONE MOST FREQUENT DESCRIPTION.
# TIED_DESCRIPTIONS > 1 MEANS MULTIPLE DESCRIPTIONS SHARE FIRST PLACE.
CREATE TEMPORARY TABLE top_product_descriptions AS
SELECT
    stock_code,
    product_description,
    description_count,
    COUNT(*) OVER (
        PARTITION BY stock_code
    ) AS tied_descriptions
FROM product_description_ranked
WHERE description_rank = 1;


# STEP 4: REVIEW STOCK CODES WITH TIED MOST FREQUENT DESCRIPTIONS
# EACH RESULT ROW IS ONE TIED DESCRIPTION, NOT ONE DISTINCT STOCK CODE.
# EACH AFFECTED STOCK CODE NEEDS A MANUAL RESOLUTION
# OR AN EXPLICITLY DOCUMENTED EXCLUSION BEFORE PRODUCT INSERTION.
SELECT
    stock_code,
    product_description,
    description_count,
    tied_descriptions
FROM top_product_descriptions
WHERE tied_descriptions > 1
ORDER BY
    stock_code,
    product_description;
    
    
