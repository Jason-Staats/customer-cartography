# CREATE PRODUCT TABLE
# ONE ROW PER RETAINED STOCK CODE.
# THE PRIMARY KEY PREVENTS DUPLICATE AND NULL STOCK CODES.
# PRODUCT DESCRIPTIONS MUST NOT BE NULL.
CREATE TABLE product (
    stock_code VARCHAR(20) PRIMARY KEY,
    product_description VARCHAR(255) NOT NULL
);


# INSERT PRODUCTS WITH ONE MOST FREQUENT NONBLANK DESCRIPTION
# APPLY THE DOCUMENTED EXCLUSION OF STOCK CODE 23595 EXPLICITLY.
INSERT INTO product (
    stock_code,
    product_description
)
SELECT
    stock_code,
    product_description
FROM top_product_descriptions
WHERE tied_descriptions = 1
  AND stock_code <> '23595';


# INSERT MANUALLY RESOLVED PRODUCTS
INSERT INTO product (
    stock_code,
    product_description
)
SELECT
    stock_code,
    product_description
FROM product_description_overrides
WHERE stock_code <> '23595';


# VERIFY PRODUCT COUNT AGAINST THE SELECTED INPUTS
# VALIDATION: ACTUAL AND EXPECTED COUNTS MUST MATCH.
# THE PRE-INSERT CHECKS MUST PASS FOR THIS COMPARISON TO BE MEANINGFUL.
SELECT
    (SELECT COUNT(*) FROM product) AS product_count,
    (
        SELECT COUNT(*)
        FROM top_product_descriptions
        WHERE tied_descriptions = 1
          AND stock_code <> '23595'
    ) + (
        SELECT COUNT(*)
        FROM product_description_overrides
        WHERE stock_code <> '23595'
    ) AS expected_product_count;


# VERIFY EVERY PRODUCT HAS A NONBLANK DESCRIPTION
# VALIDATION: EXPECTED ZERO ROWS.
SELECT
    stock_code,
    product_description
FROM product
WHERE NULLIF(TRIM(product_description), '') IS NULL
ORDER BY stock_code;


# VERIFY EVERY MANUAL SELECTION WAS INSERTED WITH ITS CHOSEN DESCRIPTION
# VALIDATION: EXPECTED ZERO ROWS.
# THE LEFT JOIN ALSO DETECTS MISSING PRODUCTS.
SELECT
    o.stock_code,
    o.product_description AS selected_description,
    p.product_description AS inserted_description
FROM product_description_overrides o
LEFT JOIN product p
    ON o.stock_code = p.stock_code
WHERE p.stock_code IS NULL
   OR NOT (p.product_description <=> o.product_description)
ORDER BY o.stock_code;


# VERIFY THE INTENTIONALLY EXCLUDED STOCK CODE IS ABSENT
# VALIDATION: EXPECTED ZERO ROWS.
SELECT
    stock_code,
    product_description
FROM product
WHERE stock_code = '23595';


# CHECK FOR UNEXPECTEDLY EXCLUDED STOCK CODES
# VALIDATION: EXPECTED ZERO ROWS.
# ANY CODE WITH A NONBLANK SOURCE DESCRIPTION SHOULD BE RETAINED,
# EXCEPT THE DOCUMENTED EXCLUSION OF 23595.
