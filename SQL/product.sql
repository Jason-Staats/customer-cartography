# THIS SCRIPT:
# SELECTS ONE DESCRIPTION PER RETAINED STOCK CODE.
# RESOLVES SELECTED DESCRIPTION TIES MANUALLY.
# RETAIL_STG REMAINS UNCHANGED.
# STOCK CODES EXCLUDED HERE ARE ALSO EXCLUDED FROM INVOICE_LINE.

# PRODUCT MEMBERSHIP INDICATES A RETAINED STOCK CODE WITH A SELECTED DESCRIPTION.
# IT DOES NOT ESTABLISH THAT THE CODE REPRESENTS MERCHANDISE.
